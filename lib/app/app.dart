/// Root widget.
///
/// Does what `M3EMaterialApp` does (Material themes from [M3EThemeData] plus
/// the M3E theme for the subtree) but on top of `MaterialApp.router`, which
/// `M3EMaterialApp` doesn't support, and with both brightnesses generated by
/// [AppTheme] instead of `M3ETheme`'s derived dark template. Re-check against
/// `M3EMaterialApp` when upgrading material_3_expressive.
class MihomoteApp extends ConsumerStatefulWidget {
  const MihomoteApp({super.key});

  @override
  ConsumerState<MihomoteApp> createState() => _MihomoteAppState();
}

class _MihomoteAppState extends ConsumerState<MihomoteApp> {
  Color? _seed;
  late AppTheme _theme;

  AppTheme _themeFor(Color seed) {
    if (seed != _seed) {
      _seed = seed;
      _theme = AppTheme.fromSeed(seed);
    }
    return _theme;
  }

  @override
  Widget build(BuildContext context) {
    final settings = ref.watch(appSettingsProvider);
    final seed = settings.seedColor ?? defaultSeedColor;
    // The host stays mounted while dynamic color is toggled so the app below
    // keeps its state; only the seed changes.
    if (supportsDynamicColor) {
      return M3EDynamicColorHost(
        builder: (light, _) => _app(
          settings,
          _themeFor(settings.dynamicColor ? light?.primary ?? seed : seed),
        ),
      );
    }
    return _app(settings, _themeFor(seed));
  }

  Widget _app(AppSettings settings, AppTheme theme) {
    return MaterialApp.router(
      routerConfig: ref.watch(routerProvider),
      onGenerateTitle: (context) => context.l10n.appTitle,
      debugShowCheckedModeBanner: false,
      // Brightness changes are animated by _ThemeTransition instead:
      // M3EResolvedTheme reads the parent Theme without depending on it, so
      // MaterialApp's own animation left dark cards on a light scaffold.
      themeAnimationDuration: Duration.zero,
      theme: theme.lightMaterial,
      darkTheme: theme.darkMaterial,
      themeMode: settings.themeMode,
      locale: settings.locale,
      supportedLocales: AppLocalizations.supportedLocales,
      // material_ui's delegates, not the framework ones that
      // AppLocalizations.localizationsDelegates would pull in (AGENTS.md §3.1).
      localizationsDelegates: const [
        AppLocalizations.delegate,
        ...GlobalMaterialLocalizations.delegates,
      ],
      builder: (context, child) => _ThemeTransition(
        theme: theme,
        brightness: Theme.of(context).brightness,
        child: _SystemBarsStyle(child: child ?? const SizedBox.shrink()),
      ),
    );
  }
}

/// Applies [theme] for [brightness], fading through the colors when the
/// brightness changes. Each frame lerps one color scheme and hands it to both
/// the Material theme and the M3E theme, so the two never disagree.
class _ThemeTransition extends StatefulWidget {
  const _ThemeTransition({
    required this.theme,
    required this.brightness,
    required this.child,
  });

  final AppTheme theme;
  final Brightness brightness;
  final Widget child;

  @override
  State<_ThemeTransition> createState() => _ThemeTransitionState();
}

class _ThemeTransitionState extends State<_ThemeTransition>
    with SingleTickerProviderStateMixin {
  late final AnimationController _progress = AnimationController(
    vsync: this,
    duration: const Duration(milliseconds: 350),
    value: _target,
  );

  double get _target => widget.brightness == Brightness.dark ? 1 : 0;

  @override
  void didUpdateWidget(_ThemeTransition oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.brightness == widget.brightness) return;
    if (MediaQuery.disableAnimationsOf(context)) {
      _progress.value = _target;
    } else {
      _progress.animateTo(_target, curve: Curves.easeInOut);
    }
  }

  @override
  void dispose() {
    _progress.dispose();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return AnimatedBuilder(
      animation: _progress,
      child: widget.child,
      builder: (context, child) {
        final theme = widget.theme;
        final (material, expressive) = switch (_progress.value) {
          0.0 => (theme.lightMaterial, theme.light),
          1.0 => (theme.darkMaterial, theme.dark),
          final t => theme.lerp(t),
        };
        return Theme(
          data: material,
          child: M3EResolvedTheme(data: expressive, child: child!),
        );
      },
    );
  }
}

/// Transparent system bars with icons that contrast the current theme.
class _SystemBarsStyle extends StatelessWidget {
  const _SystemBarsStyle({required this.child});

  final Widget child;

  @override
  Widget build(BuildContext context) {
    final dark = Theme.of(context).brightness == Brightness.dark;
    final icons = dark ? Brightness.light : Brightness.dark;
    return AnnotatedRegion<SystemUiOverlayStyle>(
      value: SystemUiOverlayStyle(
        statusBarColor: Colors.transparent,
        systemNavigationBarColor: Colors.transparent,
        statusBarIconBrightness: icons,
        systemNavigationBarIconBrightness: icons,
        statusBarBrightness: dark ? Brightness.dark : Brightness.light,
        systemNavigationBarContrastEnforced: false,
      ),
      child: child,
    );
  }
}
