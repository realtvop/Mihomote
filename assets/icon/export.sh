#!/usr/bin/env bash
# Regenerates every platform's launcher icon from assets/icon/mihomote.svg.
# Needs ImageMagick 7 (perl ships with macOS). Usage: bash assets/icon/export.sh
set -euo pipefail

cd "$(dirname "$0")/../.."

T="build/icon-export"
rm -rf "$T"
mkdir -p "$T"
export MAGICK_TEMPORARY_PATH="$T"
trap 'rm -rf "$T"' EXIT

# Every size is downscaled once from a 4096 render, which keeps small icons crisp.
# Master A: the full-bleed square, for surfaces that apply their own mask.
magick -background none -density 384 assets/icon/mihomote.svg "$T/A_4096.png"

# Master B: rounded tile (22.5% corners, as on macOS) for surfaces that show the
# icon unmasked.
sed 's/<rect id="background" width="1024" height="1024"/<rect id="background" width="1024" height="1024" rx="230.4"/' assets/icon/mihomote.svg > "$T/B.svg"
magick -background none -density 384 "$T/B.svg" "$T/B_4096.png"
magick "$T/B_4096.png" -resize 1024x1024 -strip -define png:exclude-chunks=date,time "PNG32:$T/B_1024.png"

# Master C: macOS applies no mask, so the icon carries the 824/1024 body and the
# Big Sur drop shadow itself.
magick "$T/B_4096.png" -resize 824x824 -background none -gravity center -extent 1024x1024 "$T/C_flat.png"
magick "$T/C_flat.png" \( +clone -fill black -colorize 100 -channel A -blur 0x5 -evaluate multiply 0.3 +channel -roll +0+10 \) +swap -background none -compose over -composite "$T/C_1024.png"

# iOS masks the icon itself, and App Store Connect rejects icons with alpha.
IOS_DIR="ios/Runner/Assets.xcassets/AppIcon.appiconset"
mkdir -p "$IOS_DIR"
declare -a IOS_ICONS=(
  "20x20:Icon-App-20x20@1x.png"
  "40x40:Icon-App-20x20@2x.png"
  "60x60:Icon-App-20x20@3x.png"
  "29x29:Icon-App-29x29@1x.png"
  "58x58:Icon-App-29x29@2x.png"
  "87x87:Icon-App-29x29@3x.png"
  "40x40:Icon-App-40x40@1x.png"
  "80x80:Icon-App-40x40@2x.png"
  "120x120:Icon-App-40x40@3x.png"
  "120x120:Icon-App-60x60@2x.png"
  "180x180:Icon-App-60x60@3x.png"
  "76x76:Icon-App-76x76@1x.png"
  "152x152:Icon-App-76x76@2x.png"
  "167x167:Icon-App-83.5x83.5@2x.png"
  "1024x1024:Icon-App-1024x1024@1x.png"
)

for item in "${IOS_ICONS[@]}"; do
  size="${item%%:*}"
  filename="${item##*:}"
  magick "$T/A_4096.png" -resize "$size" -alpha off -strip -define png:exclude-chunks=date,time "PNG24:$IOS_DIR/$filename"
done

# macOS: master C at every size the asset catalog lists.
MACOS_DIR="macos/Runner/Assets.xcassets/AppIcon.appiconset"
mkdir -p "$MACOS_DIR"
for sz in 16 32 64 128 256 512 1024; do
  magick "$T/C_1024.png" -resize "${sz}x${sz}" -strip -define png:exclude-chunks=date,time "PNG32:$MACOS_DIR/app_icon_${sz}.png"
done

# Legacy launcher icons; only API 24-25 use them (minSdk is 24).
declare -a ANDROID_MIPMAPS=(
  "48x48:mipmap-mdpi"
  "72x72:mipmap-hdpi"
  "96x96:mipmap-xhdpi"
  "144x144:mipmap-xxhdpi"
  "192x192:mipmap-xxxhdpi"
)

for item in "${ANDROID_MIPMAPS[@]}"; do
  size="${item%%:*}"
  dpi="${item##*:}"
  dir="android/app/src/main/res/$dpi"
  mkdir -p "$dir"
  magick "$T/B_4096.png" -resize "$size" -strip -define png:exclude-chunks=date,time "PNG32:$dir/ic_launcher.png"
done

# Web: browsers show "any" icons and the favicon unmasked, while maskable icons
# and the apple-touch-icon need the opaque full-bleed square.
mkdir -p web/icons
magick "$T/B_4096.png" -resize 192x192 -strip -define png:exclude-chunks=date,time "PNG32:web/icons/Icon-192.png"
magick "$T/B_4096.png" -resize 512x512 -strip -define png:exclude-chunks=date,time "PNG32:web/icons/Icon-512.png"
magick "$T/A_4096.png" -resize 192x192 -alpha off -strip -define png:exclude-chunks=date,time "PNG24:web/icons/Icon-maskable-192.png"
magick "$T/A_4096.png" -resize 512x512 -alpha off -strip -define png:exclude-chunks=date,time "PNG24:web/icons/Icon-maskable-512.png"
magick "$T/B_4096.png" -resize 32x32 -strip -define png:exclude-chunks=date,time "PNG32:web/favicon.png"

# Windows picks the closest of these sizes for Explorer, the taskbar and the installer.
mkdir -p windows/runner/resources
magick "$T/B_1024.png" -define icon:auto-resize=256,128,64,48,32,24,16 windows/runner/resources/app_icon.ico

# Android adaptive foreground, generated from the SVG so the two cannot drift apart.
# Scaling by 2/3 maps the 1024 master onto the visible 72dp of the 108dp canvas,
# keeping the knob inside the 66dp safe zone; it doubles as the monochrome layer.
mkdir -p android/app/src/main/res/drawable
KNOB_D=$(perl -0777 -ne 'print $1 if /id="knob"[^>]*?\sd="([^"]+)"/s' assets/icon/mihomote.svg | tr '\n' ' ' | tr -s ' ' | sed 's/^ //; s/ $//')

cat <<EOF > android/app/src/main/res/drawable/ic_launcher_foreground.xml
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by assets/icon/export.sh from assets/icon/mihomote.svg. Do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="1024"
    android:viewportHeight="1024">
    <group
        android:pivotX="512"
        android:pivotY="512"
        android:scaleX="0.6667"
        android:scaleY="0.6667">
        <path
            android:fillColor="#E7E7FF"
            android:fillType="evenOdd"
            android:pathData="${KNOB_D}" />
    </group>
</vector>
EOF
